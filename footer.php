    // Bulletproof Regional Coverage Tab Switcher (Global Markets <-> India Network)
    function switchCoverageTab(targetTabId) {
        var globalBtn = document.getElementById('tab-global-btn');
        var indiaBtn = document.getElementById('tab-india-btn');
        var globalPane = document.getElementById('tab-global');
        var indiaPane = document.getElementById('tab-india');

        if (targetTabId === 'tab-india' || targetTabId === 'india') {
            if (globalBtn) {
                globalBtn.classList.remove('active');
                globalBtn.setAttribute('aria-selected', 'false');
            }
            if (indiaBtn) {
                indiaBtn.classList.add('active');
                indiaBtn.setAttribute('aria-selected', 'true');
            }
            if (globalPane) {
                globalPane.classList.remove('show', 'active');
                globalPane.style.setProperty('display', 'none', 'important');
            }
            if (indiaPane) {
                indiaPane.classList.add('show', 'active');
                indiaPane.style.setProperty('display', 'block', 'important');
            }
        } else {
            if (indiaBtn) {
                indiaBtn.classList.remove('active');
                indiaBtn.setAttribute('aria-selected', 'false');
            }
            if (globalBtn) {
                globalBtn.classList.add('active');
                globalBtn.setAttribute('aria-selected', 'true');
            }
            if (indiaPane) {
                indiaPane.classList.remove('show', 'active');
                indiaPane.style.setProperty('display', 'none', 'important');
            }
            if (globalPane) {
                globalPane.classList.add('show', 'active');
                globalPane.style.setProperty('display', 'block', 'important');
            }
        }
    }

    $(document).ready(function() {
