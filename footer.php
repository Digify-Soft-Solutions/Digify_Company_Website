    // Footer City Search and Zone Filter
    document.addEventListener('DOMContentLoaded', function() {
        const searchInput = document.getElementById('footerCitySearch');
        const citiesList = document.getElementById('footerCitiesList');
        const zoneBtns = document.querySelectorAll('.zone-pill-btn');
        
        if (citiesList) {
            const cityLinks = citiesList.querySelectorAll('.city-pill-link');
            let currentZone = 'all';

            function filterCities() {
                const query = searchInput ? searchInput.value.toLowerCase().trim() : '';
                let visibleCount = 0;

                cityLinks.forEach(link => {
                    const cityName = link.getAttribute('data-name') || link.textContent.toLowerCase();
                    const cityZone = link.getAttribute('data-zone') || '';

                    const matchesSearch = !query || cityName.includes(query);
                    const matchesZone = (currentZone === 'all') || (cityZone === currentZone);

                    if (matchesSearch && matchesZone) {
                        link.style.display = 'inline-flex';
                        visibleCount++;
                    } else {
                        link.style.display = 'none';
                    }
                });

                let noResults = document.getElementById('noCityResultsNotice');
                if (visibleCount === 0) {
                    if (!noResults) {
                        noResults = document.createElement('div');
                        noResults.id = 'noCityResultsNotice';
                        noResults.className = 'w-100 py-3 text-center text-white-50 small';
                        noResults.innerHTML = '<i class="fa-solid fa-circle-info me-1 text-warning"></i> No commerce hubs found matching your criteria.';
                        citiesList.appendChild(noResults);
                    }
                } else if (noResults) {
                    noResults.remove();
                }
            }

            if (searchInput) {
                searchInput.addEventListener('input', filterCities);
            }

            zoneBtns.forEach(btn => {
                btn.addEventListener('click', function() {
                    zoneBtns.forEach(b => b.classList.remove('active'));
                    this.classList.add('active');
                    currentZone = this.getAttribute('data-zone');
                    filterCities();
                });
            });
        }
    });
